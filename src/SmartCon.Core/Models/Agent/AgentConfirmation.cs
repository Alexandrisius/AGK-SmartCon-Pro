namespace SmartCon.Core.Models.Agent;

public enum AgentConfirmationResult
{
    Approved = 0,
    Rejected = 1,
    TimedOut = 2,
    Cancelled = 3
}

/// <summary>
/// Request shown to the user before a write tool changes the model.
/// The digest binds the approval to the exact canonical action, so a
/// changed argument set requires a new approval (mvp-plan §9.8 L3).
/// </summary>
public sealed class AgentConfirmationRequest
{
    public required string ToolName { get; init; }

    public required string Operation { get; init; }

    public required string Summary { get; init; }

    public required string Digest { get; init; }

    public required string ArgumentsJson { get; init; }

    public IReadOnlyList<string> Risks { get; init; } = Array.Empty<string>();

    public int AffectedCount { get; init; }

    public bool Reversible { get; init; } = true;

    public TimeSpan Timeout { get; init; } = TimeSpan.FromMinutes(5);

    /// <summary>
    /// Single-use approval nonce. Generated by the caller (plan executor) or by
    /// the confirmation service; an approval cannot be replayed with the same nonce.
    /// </summary>
    public string Nonce { get; init; } = string.Empty;

    /// <summary>Moment after which the approval is no longer valid.</summary>
    public DateTime? ExpiresAt { get; init; }

    /// <summary>
    /// Canonical digest of the whole plan for plan-level approvals (L3). Tool-level
    /// confirmations leave it null and bind only <see cref="Digest"/>.
    /// </summary>
    public string? PlanDigest { get; init; }
}
