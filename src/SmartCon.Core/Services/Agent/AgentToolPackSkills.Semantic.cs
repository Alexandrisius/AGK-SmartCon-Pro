    private static IEnumerable<(string Pack, string Markdown)> SemanticSkills() =>
        new[] { ("semantic", Semantic) };

    private const string Semantic = @"## Пак semantic: семантический выбор и классификаторы

### Карта тулов
- `read_classifier` — парсит иерархический txt-классификатор (коды «30.20.10»,
  русские названия, отступы/табы) в items: `{code, breadcrumb, level, name,
  line, children}`; крошки уже сшиты «раздел › подраздел › элемент»; кодировка
  авто (UTF-8 → Windows-1251), комментарии `#`/`//` и пустые строки
  пропускаются; `maxLines` (по умолчанию 2000) обрезает с `truncated=true`.
- `semantic_match` — семантический выбор топ-K из массива строк (до 500):
  малая модель принятия решений ранжирует candidates по `query`, возвращает
  `matches[{id, score, rank}]`; `topK` 1..10, `minScore` (по умолчанию 0.08),
  `instructions` — контекст выбора. Список режется на Choice-вопросы по 255
  опций и мержится.

### Кухня
- Экономия контекста — суть пака: сырой файл классификатора и весь список
  строк НЕ читаются в контекст. `read_classifier` отдаёт только
  структурированные строки, `semantic_match` — только топ-K. 120 строк
  классификатора ≈ 1 вызов вместо ~120 строк в контексте.
- `semantic_match` работает через decision-инфраструктуру (тот же канал, что
  маршрутизация тулов). Если малая модель не настроена или отказала — тул
  отвечает `decision_unavailable` с hint: это НЕ ошибка кейса; читай строки
  сам (для классификатора — уже разобранные items из `read_classifier`,
  пачками) или покажи короткий список пользователю. Главный критерий —
  верные коды, экономия — бонус.
- Формат кода: `\d{2}(\.\d{2}){0,2}` — уровень = число сегментов («30» —
  раздел, «30.20» — подраздел, «30.20.10» — элемент). Строки без кода на более
  глубоком отступе — дети предыдущей кодовой строки (попадают в `children`,
  обогащают подбор, но сами не выбираются).
- Скоры — вероятности 0..1; `minScore` отсекает мусор ниже 0.08; при пустом
  `matches` снизь `minScore` или переформулируй `query`, не выдумывай коды
  мимо списка.
- Идентификаторы: у items из `read_classifier` id=code, text=breadcrumb —
  передавай их в `semantic_match` как есть; для ФОПа id = имя/номер параметра,
  text = название.
- `read_classifier` читает файл только по абсолютному пути из задачи; ошибки
  типизированы (`file_not_found`, `file_read_failed`), ничего не пишет в модель.

### Рецепты
- Классификатор (кейс «код по классификатору»): `semantic_match(classifierPath=..., codePrefix=""30."")`
  — компактный режим, файл читается сам, аргумент ~100 байт. НЕ собирай items вручную по read_classifier:
  инлайн-массив в каждом параллельном вызове раздувает аргументы и обрезается LLM (#470).

1. «Заполни код по классификатору» (кейс 5): для каждого семейства/типа собрать
   описание (категория, имя, общие параметры, типоразмер) → `semantic_match(
   classifierPath=..., codePrefix=ветка, query=описание, instructions=«обычно
   одному семейству один код; типоразмеры трубы сталь/медь/ПВХ — разные
   коды»)` → запись выбранного кода всем типоразмерам одним `set_parameters`
   (items по typeIds; AssemblyCode — параметр ТИПОРАЗМЕРА: один код = запись
   в каждый тип). Неуверенные (низкий score) — отдельным списком.
2. «ФОП заказчика: какой параметр похож на наш» (кейс 2): столбец наименований
   ФОПа (100-200 строк) → items `[{id: параметр, text: наименование}]` →
   `semantic_match(query=имя нашего параметра + смысл, topK=3)` → маппинг для
   `map_family_parameters`/`replace_family_parameter`.
3. Несколько запросов подряд по одному классификатору: один
   `read_classifier`, затем N дешёвых `semantic_match` — items уже в
   контексте одним компактным массивом.

### Что нельзя
- Писать коды/параметры руками тулами этого пака — он read-only; запись —
  write-туры params/families.
- Выдумывать коды, которых нет в items (`matches` пуст → скажи честно).
- Обходить `decision_unavailable` повторными вызовами — переходи на ручной
  разбор строк или вопрос пользователю.
- Читать файлы классификатора через произвольные пути вне задачи — путь
  называется пользователем.
";
}
