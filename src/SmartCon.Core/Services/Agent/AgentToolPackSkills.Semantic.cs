    private const string Semantic = @"## Пак semantic: выбор из больших списков и классификация

### Карта тулов
- `semantic_match` — семантический выбор топ-K из массива строк (до 500): малая модель
  принятия решений ранжирует candidates по `query`, возвращает `matches[{id, score, rank}]`
  (topK 1..10, minScore по умолчанию 0.08, `instructions` — контекст выбора). Список режется
  на Choice-вопросы по 255 опций и мержится. Пакетный режим: `queries=[{id, query}]` — до 20
  запросов за один вызов по одному списку; компактный режим классификатора:
  `classifierPath` (+ `codePrefix`) — строки читаются из файла самим тулом (в подборе
  участвуют первые 500 строк после фильтра `codePrefix`: в большом классификаторе сужай
  ветку через `codePrefix`).
- `read_classifier(path)` — парсит иерархический txt-классификатор (коды, названия,
  отступы/табы) в items `{code, breadcrumb, level, name, line, children}`; крошки уже сшиты
  «раздел › подраздел › элемент»; кодировка авто (UTF-8 → Windows-1251), комментарии
  `#`/`//` пропускаются; `maxLines` (по умолчанию 2000) обрезает с `truncated=true`.
  Парсер узнаёт только коды из 1–3 двузначных сегментов через точку (уровень = число
  сегментов); строки без кода на более глубоком отступе попадают в `children` предыдущей
  кодовой строки и сами кодом не становятся; `path` — абсолютный путь.

### Откуда брать коды классификации
- Источник истины — сам классификатор: таблица, загруженная в документ, либо файл, который
  назван в задаче. Код, которого нет в источнике, не существует.
- Сначала проверь таблицу документа (тул чтения записей классификатора; пикер
  «Код по классификатору» показывает именно её). Если таблица не загружена — скажи
  пользователю прямо: «в проекте не загружен классификатор». Не подбирай код по аналогии
  с другими элементами и не переноси коды из других проектов или семейств. Предложи
  пользователю загрузить классификатор в Revit или назвать файл.
- `read_classifier(path)` — только когда в задаче назван файл классификатора. Путь даёт задача;
  если файл лежит в папке модели, папку берут из `get_project_overview`. Файл, которого задача
  не называла, не ищут и не перебирают.
- Справочные значения вообще (коды, марки, артикулы, стандарты) не выводят по аналогии —
  их подтверждают источником или спрашивают у пользователя.

### Кухня
- Экономия контекста — суть пака: сырой файл классификатора и весь список строк НЕ читаются
  в контекст. `read_classifier` отдаёт только структурированные строки,
  `semantic_match` — только топ-K.
- `semantic_match` работает через decision-инфраструктуру (тот же канал, что маршрутизация
  тулов). Если малая модель не настроена или отказала — тул отвечает `decision_unavailable`
  с hint: это НЕ ошибка задачи; читай строки сам пачками (items из `read_classifier`) или
  покажи короткий список пользователю. Главный критерий — верные значения, экономия — бонус.
- Формат кода бывает любой (точки, буквы, тире, разная глубина) — не предполагай формат,
  бери коды из источника как есть. Элементам обычно назначают листовые коды; узлы выше —
  для навигации и хлебных крошек.
- Скоры — вероятности 0..1; `minScore` отсекает мусор; при пустом `matches` сузь список,
  переформулируй `query` или снизь `minScore`, но не выдумывай значений.
- Идентификаторы: у items классификатора id=code, text=breadcrumb — передавай их в
  `semantic_match` как есть; при сопоставлении параметров id = имя/номер параметра,
  text = название.

### Рецепты
- МНОГО запросов — ОДИН вызов: `semantic_match(queries=[{id:ключ, query:описание}, …])` —
  не вызывай тул по одному запросу на объект (шторм вызовов губит задачу).
- «Присвой коды классификатора»: источник (таблица документа или файл) → `semantic_match`
  батчем по семействам: query = описание (категория, имя семейства, описание/назначение/
  материал, имя типоразмера), instructions = «обычно одному семейству подходит один код;
  если типоразмеры одного семейства различаются по сути — у каждого свой код» → запись
  ОДНИМ `set_parameters` с items по всем типоразмерам (код классификации — параметр
  ТИПОРАЗМЕРА: один код записывается в каждый типоразмер отдельно) → read-back → отчёт:
  семейство → код + путь по классификатору; отдельно — что не удалось классифицировать
  уверенно.
- «Что из списка X больше всего похоже на Y» (сопоставление списков: классификаторы,
  общие параметры): items=[{id, text}] → `semantic_match(query=Y, topK=3)` → результат
  для тулов маппинга/замены.
- Несколько запросов по одному списку: ОДИН вызов с `queries=[{id,query}…]` (до 20).

### Что нельзя
- Писать значения тулами этого пака — он read-only; запись — write-туры params/families.
- Выдумывать коды, которых нет в источнике (`matches` пуст → скажи честно).
- Подбирать коды, имена или стандарты «по аналогии» с другими элементами, когда источник
  недоступен, — сообщи пользователю, чего не хватает.
- Обходить `decision_unavailable` повторными вызовами — переходи на ручной разбор строк
  или вопрос пользователю.
- Читать файлы классификатора по путям, которых нет в задаче: для встроенного классификатора
  путь не нужен вообще, для внешнего файла путь даёт задача или пользователь.
";
}
