    private static IEnumerable<(string Pack, string Markdown)> SemanticSkills() =>
        new[] { ("semantic", Semantic) };

    private const string Semantic = @"## Пак semantic: выбор из больших списков и классификация

### Карта тулов
- `semantic_match` — семантический выбор топ-K из массива строк (до 500): малая модель
  принятия решений ранжирует candidates по `query`, возвращает `matches[{id, score, rank}]`
  (topK 1..10, minScore по умолчанию 0.08, `instructions` — контекст выбора). Список режется
  на Choice-вопросы по 255 опций и мержится. Пакетный режим: `queries=[{id, query}]` — до 20
  запросов за один вызов по одному списку; компактный режим классификатора:
  `classifierPath` (+ `codePrefix`) — строки читаются из файла самим тулом (в подборе
  участвуют первые 500 строк после фильтра `codePrefix`: в большом классификаторе сужай
  ветку через `codePrefix` — начало кода как текст, `30.20` или `A10`).
- `read_classifier(path)` — парсит иерархический txt-классификатор (коды, названия,
  отступы/табы) в items `{code, breadcrumb, level, name, line, children}`; крошки уже сшиты
  «раздел › подраздел › элемент»; кодировка авто (UTF-8 → Windows-1251), комментарии
  `#`/`//` пропускаются; `maxLines` (по умолчанию 2000) обрезает с `truncated=true`.
  Код стоит в начале строки: числа с сегментами через точку любой глубины (`30`, `30.20.10.10`)
  или буквенный префикс с цифрами (`A1010`, `A1010.10`); уровень точечного кода = число
  сегментов, буквенного без точек — по отступу. Строки без кода на более глубоком отступе
  попадают в `children` предыдущей кодовой строки и сами кодом не становятся;
  `path` — абсолютный путь.
- `list_classification_entries` — записи таблицы классификации, загруженной в документ;
  `classify_types` — подбор кодов типоразмерам по этой таблице одним вызовом;
  `load_classification_table(path)` — подключает файл таблицы к документу (см. раздел
  «Классификация» ниже).

### Откуда брать коды классификации
- Источник истины — сам классификатор: таблица, загруженная в документ, либо файл, который
  назван в задаче. Код, которого нет в источнике, не существует.
- Сначала проверь таблицу документа (`list_classification_entries` — её показывает пикер
  «Код по классификатору»). Если таблица не загружена — скажи пользователю прямо:
  «в проекте не загружен классификатор». Не подбирай код по аналогии с другими элементами и не
  переноси коды из других проектов или семейств. Предложи пользователю загрузить
  классификатор в Revit, назвать файл таблицы или назвать нужные коды самому.
- `read_classifier(path)` — только когда в задаче назван файл классификатора. Путь даёт задача;
  если файл лежит в папке модели, папку берут из `get_project_overview`. Файл, которого задача
  не называла, не ищут и не перебирают.
- Справочные значения вообще (коды, марки, артикулы, стандарты) не выводят по аналогии —
  их подтверждают источником или спрашивают у пользователя.

### Кухня
- Экономия контекста — суть пака: сырой файл классификатора и весь список строк НЕ читаются
  в контекст. `read_classifier` отдаёт только структурированные строки,
  `semantic_match` — только топ-K.
- `semantic_match` работает через decision-инфраструктуру (тот же канал, что маршрутизация
  тулов). Если малая модель не настроена или отказала — тул отвечает `decision_unavailable`
  с hint: это НЕ ошибка задачи; читай строки сам пачками (items из `read_classifier`) или
  покажи короткий список пользователю. Главный критерий — верные значения, экономия — бонус.
- Формат кода бывает любой (точки, буквы, тире, разная глубина) — не предполагай формат,
  бери коды из источника как есть. Элементам обычно назначают листовые коды; узлы выше —
  для навигации и хлебных крошек.
- Скоры — вероятности 0..1; `minScore` отсекает мусор; при пустом `matches` сузь список,
  переформулируй `query` или снизь `minScore`, но не выдумывай значений.
- Идентификаторы: у items классификатора id=code, text=breadcrumb — передавай их в
  `semantic_match` как есть; при сопоставлении параметров id = имя/номер параметра,
  text = название.

### Рецепты
- МНОГО запросов — ОДИН вызов: `semantic_match(queries=[{id:ключ, query:описание}, …])` —
  не вызывай тул по одному запросу на объект (шторм вызовов губит задачу).
- «Присвой коды классификатора» (таблица загружена в документ): `classify_types` ОДНИМ
  вызовом — выборка и подбор уже внутри → `set_parameters` (dryRun → apply) с готовым
  `setParameters.items` из результата → read-back → отчёт: семейство → код + путь по
  классификатору; отдельно — `uncertain`: предложи пользователю решить по этим семействам.
- «Присвой коды классификатора» (в задаче назван ФАЙЛ классификатора): файл в формате экспорта
  Revit — подключи его `load_classification_table(path)` и действуй как выше. Файл другого
  формата — `read_classifier(path)` → `semantic_match` батчем `queries=[{id,query}…]`
  (query = описание: категория, имя семейства, описание/назначение/материал, имя
  типоразмера; instructions = «обычно одному семейству подходит один код; если типоразмеры
  одного семейства различаются по сути — у каждого свой код»). Запись таких кодов возможна
  только с `allowUnverifiedClassification:true` — сначала скажи пользователю, что таблица
  в проект не загружена и коды сверить не с чем, и спроси.
- «Что из списка X больше всего похоже на Y» (сопоставление списков: классификаторы,
  общие параметры): items=[{id, text}] → `semantic_match(query=Y, topK=3)` → результат
  для тулов маппинга/замены.
- Несколько запросов по одному списку: ОДИН вызов с `queries=[{id,query}…]` (до 20).

### Что нельзя
- Писать значения тулами этого пака — он read-only; запись — write-туры params/families.
- Выдумывать коды, которых нет в источнике (`matches` пуст → скажи честно).
- Подбирать коды, имена или стандарты «по аналогии» с другими элементами, когда источник
  недоступен, — сообщи пользователю, чего не хватает.
- Обходить `decision_unavailable` повторными вызовами — переходи на ручной разбор строк
  или вопрос пользователю.
- Читать файлы классификатора по путям, которых нет в задаче: для встроенного классификатора
  путь не нужен вообще, для внешнего файла путь даёт задача или пользователь.

### Классификация: таблица, загруженная в документ
- `list_classification_entries` читает таблицу классификации, ЗАГРУЖЕННУЮ В ДОКУМЕНТ (то, что
  показывает пикер «Код по классификатору»). Путь к файлу не нужен. Фильтры: `contains`
  (подстрока кода/названия/пути), `parentCode` (ветка), `level`, `leafOnly` (по умолчанию true —
  элементам назначают листовые коды). id=code, text=breadcrumb — готовые items для `semantic_match`.
- Ответ `classification_table_not_loaded` означает: в документе классификатор НЕ загружен —
  скажи это пользователю прямо и действуй по правилу «Откуда брать коды классификации».
  Варианты: (а) пользователь загружает классификатор в Revit (Управление → Настройки
  классификации; в старых версиях — Дополнительные настройки → Код по классификатору);
  (б) пользователь называет файл — тогда `load_classification_table(path)` подключит его
  к документу; (в) пользователь сам называет код — тогда запиши его с
  `allowUnverifiedClassification:true`.
- `set_parameters` отклонит код, которого нет в загруженной таблице (`classification_code_not_found`),
  и любой код, пока таблица не загружена (`classification_table_not_loaded`), — пока не передан
  `allowUnverifiedClassification:true`. Передавай его ТОЛЬКО когда код назвал пользователь дословно.
- `classify_types` — подбор кода для типоразмеров по таблице, ЗАГРУЖЕННОЙ В ДОКУМЕНТ, одним
  вызовом: выбирает типы (категории, семейства, `onlyEmpty` — по умолчанию только без кода),
  семантически подбирает листовой код для каждого семейства и типоразмера, возвращает
  `assignments` (семейство → код + путь по классификатору), `uncertain` (что не удалось
  классифицировать уверенно) и готовый `setParameters.items`. Это read-тул: сам он ничего
  не пишет. Если таблица не загружена — ответ `classification_table_not_loaded`: скажи
  пользователю (см. выше), не подбирай коды по аналогии.
- `load_classification_table(path)` — write-тул: файл — таб-разделённый экспорт Revit
  («код, название, уровень, категория»), кириллица — в UTF-16. Откатывается только Undo в Revit.
";
}
