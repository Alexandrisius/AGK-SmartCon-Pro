    private const string Documents = @"## Пак documents: мульти-модельность

Скрытное чтение чужих моделей: открыть эталон в фоне → прочитать read-турами → сделать так же
в основной модели → закрыть донор. Пользователь ничего не видит на экране.

### Карта тулов
- `open_model_background` — скрытно открыть .rvt по абсолютному пути (без UI, активный документ не меняется). Возвращает `documentId`.
- `close_model` — закрыть донор по `documentId` или `path` без сохранения. Активный документ агент не закрывает (`model_is_active`).
- `list_known_models` — реестр «в какой модели что делали» из agent.db (путь, активность, сессии/правки/задания, сводка последней правки); `query=` ищет по сводке.

### Кухня Revit
- Открытие — `Application.OpenDocumentFile`: документ живёт в памяти без UI-фрейма и вкладки; `ActiveUIDocument` не меняется, экран пользователя не трогается.
- Донор — ТОЛЬКО чтение: в нём никогда не открываются транзакции и он никогда не сохраняется; `close_model` всегда `Close(false)`.
- Аргумент `documentId` есть только у read-тулов, читающих документ как данные (он виден в их
  схеме): без него читается активный документ, с ним — фоновый донор из реестра сессии.
  Session-тулы (`get_selected_elements`, `get_current_view_info`, `list_change_sets`,
  `get_change_set_details`, `list_shared_parameters`) его не принимают: вызов с `documentId`
  даёт `invalid_arguments`, а не чтение другого документа.
- Факт маршрутизации виден в ответе read-тура, пока открыт донор или передан `documentId`:
  поле `document` (`scope: active|background`, `documentId`). NOTE «documentId was not present
  in this call» означает: прочитан АКТИВНЫЙ документ; чтобы прочитать донора, повторите вызов
  с `documentId`.
- Открытие большой модели — секунды и сотни МБ памяти: закрывай донор сразу после чтения.
- «Уже открытая» модель не переоткрывается: тул находит её по пути среди открытых и регистрирует существующую (`wasAlreadyOpen=true`; активная — `isActive=true` + warning).
- Рабочая общая модель (central) и её локальная копия не открываются в одной сессии одновременно (`open_conflict`).

### Инварианты
- Донор только читается — правка чужих моделей и UI-активация (`OpenAndActivateDocument`) запрещены (решение владельца).
- Активная модель пользователя не меняется: все изменения — только в основную модель обычными write-тулами с подтверждением.
- Не открывать ничего без явного пути от пользователя — «самому без спроса делать не нужно»; реестр `list_known_models` не сканирует диск, он читает только то, что уже есть в agent.db.
- Один вызов = один документ: сначала `open_model_background`, потом чтения с `documentId`, в конце `close_model`. Не держи донор открытым между задачами пользователя.

### Рецепты

Рецепт фоновой работы с моделью-донором («посмотри как сделано там и сделай так же у меня»)
1. `open_model_background(path=«путь от пользователя»)` → запомнить `documentId`.
2. Read-туры с `documentId`: `list_views(documentId=…)`, `query_elements(documentId=…)`, `get_element_details(documentId=…)` — паттерн имён видов, значения параметров эталона.
3. Перенос в ОСНОВНУЮ модель обычными write-тулами без documentId (rename_views, set_parameters, …) — с подтверждением как обычно.
4. `close_model(documentId=…)` — донор закрыт, файл эталона не тронут (нет транзакций, нет сохранения).
5. Путь не назван? `list_known_models(query=«что там делали»)` → уточни у пользователя, прежде чем открывать найденное.

### Что нельзя
- Писать в донор или сохранять его.
- Открывать модели «наугад», сканируя диски или угадывая пути.
- Держать донор открытым после завершения чтения.
";
