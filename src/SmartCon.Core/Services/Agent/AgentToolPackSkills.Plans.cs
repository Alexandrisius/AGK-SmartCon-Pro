    private const string Plans = @"## Пак plans: планы изменений

`execute_plan` — многошаговый сценарий одним подтверждением: план проверяется, шаги
выполняются по порядку, результат каждого шага верифицируется чтением.

### Карта тулов
- `execute_plan` — `goal` + `steps[]`; `planDigest` связывает превью с применением.

### Формат шага
Минимальный скелет (обязательные ключи, `toolName` первым):
`{""stepId"":""s1"",""toolName"":""set_view_template"",""arguments"":{""viewId"":123,""templateId"":45}}`.
Полная форма: `{stepId, toolName, arguments, dependsOn[], onError, dryRun, expectedChanges|expectedChangesAtLeast,
readBackTool, readBackArguments, readBackExpectations[{path,expected}], rationale}`.
До 20 шагов. `dependsOn` задаёт порядок; по умолчанию шаги идут как перечислены.

### Ссылки между шагами: {""$step"": …}
Аргументы шага могут ссылаться на результат предыдущего шага: `{""$step"":""s1"",""path"":""created.sheetId""}`
— на apply это заменяется РЕАЛЬНЫМ id из результата шага s1, поэтому «создай → сразу размести/настрой»
живёт одним планом (create_sheet → create_viewports, create_schedule → place_schedule_on_sheet,
create_level → create_floor_plans). Сегменты пути — имена свойств или индексы массива
(`createdViewports.0.viewportId`); точка внутри имени не поддерживается. Формы создающих тулов:
`create_level` → `created.levelId`, `create_sheet` → `created.sheetId`, `create_schedule` →
`created.scheduleId`, `create_viewports` → `createdViewports.N.viewportId`. Ссылка сама добавляет
шаг в `dependsOn`; на превью такие шаги помечаются `preview_skipped`
(`uses_step_reference:<stepId>`) — dry-run id не выживают; неразрешённая ссылка (шаг упал, путь
не нашёлся) — typed `step_reference_unresolved`.

### Кухня Revit
- В Revit нет программного Undo: после коммита операция необратима, откат — только
  компенсацией (вернуть старые значения, удалить созданное). Поэтому план проверяет шаги
  **до** записи, а не «потом откатим».
- Атомарность в Revit даёт `TransactionGroup`: внутренние транзакции выполняются,
  при сбое `RollBack` отменяет всю группу. `Commit` группы оставляет шаги отдельными
  пунктами в меню Undo — пользователь может откатить часть.
- Если следующий шаг зависит от применённого предыдущего (например, новый вид нужно
  разместить на листе), между ними нужна отдельная транзакция-барьер, иначе второй шаг
  не увидит первый.
- `Commit` может вернуть `Pending` (документ заморожен до ответа в диалоге предупреждений);
  это не успех. `IFailuresPreprocessor` в наших транзакциях подавляет ожидаемые
  предупреждения, но не скрывает реальные отказы.
- Частичный успех внутри одной транзакции недостижим: worksharing-ошибка откатывает весь
  scope. Поэтому write-тулы сами проверяют ownership до транзакции и кладут занятые элементы
  в `skipped[]`, не доводя до отката; исполнитель отчитывается по шагам и останавливается
  на настоящем отказе.

### Инварианты
- `dryRun=true` по умолчанию: план прогоняется в режиме превью и возвращает `planDigest`.
  Применение — тот же план с `dryRun=false` и этим digest; изменённый план требует нового
  превью (`plan_digest_mismatch`).
- `planDigest` считается по шагам (id, toolName, аргументы без `dryRun`, зависимости,
  ожидаемые количества) и документу; `goal` и `rationale` в него не входят — их можно
  уточнять, не ломая подтверждение.
- `dependsOn` — только когда аргументы шага реально читают результат предыдущего шага
  (например id созданного элемента). Ложный `dependsOn` исключает шаг из превью
  (`preview_skipped`), и apply выполнит его вслепую — отчёт пометит это предупреждением.
  Для простого порядка шагов `dependsOn` не нужен: шаги идут как перечислены.
- В превью шаги, зависящие от ещё не применённой записи, пропускаются (`preview_skipped`,
  reason `depends_on_unapplied_step:<stepId>(<tool>)`); в apply они выполнятся. Флаг
  `previewIncomplete` = такие шаги есть; отчёт apply явно предупредит о них.
- Apply: по умолчанию первый упавший шаг останавливает план (`plan_apply_failed`); зависевшие от него шаги
  получают `upstream_step_failed`, прочие последующие — `not_run`. **Автоотката плана нет** —
  `undo_last` по шагам или `rollback_job`. `onError:""continue""` на шаге меняет это: сбой шага
  (в превью и в apply) считается ОЖИДАЕМЫМ — шаг помечается `expectedFailure:true`, счётчик
  `expectedFailures`, план продолжается со следующего шага. Это способ проверить guard внутри
  плана (например `copy_crop_from_view` на виде под шаблоном должен упасть
  `crop_controlled_by_template`); зависевшие от упавшего шага всё равно помечаются
  `upstream_step_failed`.
- `readBackExpectations` работает только вместе с `readBackTool` (без него план
  отклоняется на валидации) — способ доказать, что шаг сделал заявленное: путь + ожидаемое
  значение читаются после шага. Несовпадение попадает в `mismatches[]`, но общий `success`
  остаётся true — **сверяйте `mismatches`, а не только `success`**. Если read-back не задан,
  отчёт прямо скажет «verification not requested» — это не «проверено и пусто». Read-back
  без ожиданий — «read-back executed, nothing to compare»: тул вызван, ни одно значение
  не сверено. `readBackArguments` без `readBackTool` игнорируются — отчёт предупредит.
- Пути `readBackExpectations.path` адресуются по данным read-тура: `views.byId[123].templateName`
  (`byId` матчит собственный id строки — `id`, `viewId`, `scheduleId`…, а не ссылочные
  `levelId`/`templateId`), `views.byName[View 1.2].templateName` (точка внутри скобок не
  разрывает путь), `types.byId[123].values.byName[имя параметра]` (плоский словарь значений)
  или `values.[""имя.с.точкой""]` (скобки = литеральный ключ). Путь в поддерживаемой форме,
  который ничего не нашёл в ответе (нет строки или ключа), — это `mismatch` с причиной в
  скобках; `notVerifiable[]` даёт только неподдерживаемая форма пути. Сверяй путь с
  фактической формой ответа read-тура.
- `expectedChanges`/`expectedChangesAtLeast` — необязательный контракт количества. Задавай
  только число из `steps[].changed` превью шага: это собственный счётчик тула (создающий тул
  считает объект и каждое добавленное поле отдельно). В отчёте `items.changed[]` может быть
  короче — карточки, дублирующие блок `created*`, убраны и сосчитаны в
  `items.duplicatesInCreated`. Расхождение даёт `plan_fidelity_mismatch` ещё на превью; текст
  ошибки перечисляет, что тул посчитал. Не уверен в числе — не задавай.
- Id из dry-run не переживают apply: dry-run откатывается, эти id не существуют в модели.
  Превью-отчёт помечает префиксом `preview` только собственный id созданного объекта
  внутри блоков `created*` (`created[].previewViewId`, `created.previewScheduleId`) и
  ключи `wouldCreate*Id`. Ссылочные id (`levelId`, `templateId`…) не помечаются — они
  указывают на существующие объекты. Остальные id не переименовываются, но тоже dry-run:
  `changed[].id` у создающего тула. Ни один из них не используй в
  следующих шагах и в `readBackArguments` — после apply объект получает другой id, и
  read-back упадёт `*_not_found`. Внутри плана адресуй созданное `{{""$step"":…}}`-ссылкой,
  между вызовами — по имени или возьми id из отчёта apply.
- Шаг с `toolName`, которого нет в наборе доступных тулов, отклоняется на валидации: сначала
  `load_tool_pack`. `execute_plan` внутри шага запрещён.
- `allowDestructive=true` требуется для шагов, удаляющих данные; конфликт шаблон/настройки
  между шагами ловится как `plan_step_conflict`.

### Рецепты
1. «Настрой все планы этажа»: `get_view_settings` (шаг 1, чтение) → `configure_views`
   с `readBackExpectations` на итоговый `viewRange`.
2. «Переименуй виды и обнови шаблон»: два шага с `dependsOn`, у второго read-back
   `templateName`.
3. Перед планом соберите id существующих объектов: `list_views`/`query_elements` в отдельных
   вызовах. Id ТОГО, что план создаёт сам, собирать не нужно — связывайте шаги
   `{{""$step"":…}}`-ссылкой (create_level → create_floor_plans и т.п.).

### Что нельзя
- Смешивать в одном шаге несколько несвязанных тулов — один шаг = один toolName.
- Заявлять успех по `success=true` без чтения `readBackExpectations`.
- Ставить `dependsOn` «для порядка» — потеряешь превью шага.
- Реиспользовать preview-id из превью-отчёта как реальные id элементов.
- Обещать откат Revit-овским Undo: откат делает `undo_last` (наши change sets) или
  `rollback_job`, и об этом надо сказать прямо.
";

    private const string Meta = @"## Пак meta: каталог и сохранённые результаты

### Карта тулов
- `find_tools` — поиск по каталогу: `query`, `pack`, `context`, `limit/offset`. Пустой запрос — весь каталог без схем.
- `read_tool_result` — чтение результата по `resultHandle` (offset/limit или path), когда ответ был обрезан бюджетом.

### Как устроен каталог
- 62 тула в 21 паке; в каждом запросе всегда есть исследовательское ядро (11 тулов) и системные
  тулы (`load_tool_pack`, `read_tool_result`, `execute_plan`). Всё остальное не появляется само:
  его надо найти (`find_tools`) и включить (`load_tool_pack`) — агент сам решает, что нужно
  задаче, а не короткий список по первому сообщению.
- `find_tools` возвращает **карточки**: имя, пакет, риск, назначение, признак `alreadyAvailable`
  и схему. Поиск отдаёт не больше 10 карточек (по умолчанию 5), `total` в поиске — это число
  возвращённых, а не всех совпадений.
- `packHasSkill=true` в карточке значит, что у пака есть markdown-мануал: загрузите пак
  (`load_tool_pack(pack=...)`) — скил придёт один раз за диалог. Ядро и системные тулы
  (`query_elements`, `get_element_details`, `list_views`, `execute_plan`…) вызываются без
  загрузки пака, но скил их пака — нет: перед первой записью загрузите write-пак (views,
  templates, filters, families…), а для полного контракта плана — пак plans.
- Пустой `query` — листинг каталога без схем: `limit` ≤100, пагинация `offset/nextOffset`,
  `truncated`. Один пакет — `pack`.
- Карточка не даёт права вызова: сначала `load_tool_pack`. Полные примеры/синонимы —
  через `fields` (`whenToUse`, `examples`, `synonyms`, `description`).
- Принцип трёх слоёв (как в MCP/Anthropic tool search): каталог → детали → выполнение.
  Аккуратные имена и первые строки описаний решают выбор — ищите словами пользователя
  («ведомость», «фильтр», «семейство»), а не внутренними терминами.

### Кухня контекста
- Точность выбора падает после 30–50 доступных инструментов, поэтому набор ограничен, а
  остальное живёт за поиском. Полные схемы приходят только для загруженного пака.
- Бюджет результата — 40 000 символов; у `load_tool_pack` он расширен до 90 000, потому что
  его скилы приходят один раз за диалог. При превышении массивы режутся структурно
  (`truncated`, `hint`) или ответ заменяется дайджестом с `resultHandle`; полный JSON
  доступен через `read_tool_result` (хранится 30 дней).
- `read_tool_result`: `handle` — идентификатор вызова тула, `offset`/`limit` (символы,
  по умолчанию 8000) или `path` внутрь JSON (`data.groups[0]`, отрицательный индекс — с конца);
  `project:[""signatureDigest"",""parameters.name"",""count""]` возвращает только названные поля,
  а свойство над массивом разворачивает его поэлементно — не листайте 200k символов ради
  трёх полей. Ответ всегда содержит `nextOffset`.

### Инварианты
- `alreadyAvailable=true` или `alreadyLoaded` в ответе `load_tool_pack` — тул уже вызываем,
  повторная загрузка только тратит раунд.
- Если ответ обрезан и есть `resultHandle` — читайте его, а не повторяйте тот же вызов.
- Не загружайте весь каталог «на всякий случай»: каждый пак добавляет схемы и контекст.
- `find_tools` сам себя и `load_tool_pack` в выдачу не включает.

### Рецепты
1. Не знаете имя тула: `find_tools(query=""скрыть элементы на виде"")` → карточка → `load_tool_pack(pack=...)`.
2. Ответ пришёл с `truncated=true` и `resultHandle`: нужны конкретные поля —
   `read_tool_result(handle, project=[...])`; нужен весь фрагмент — `read_tool_result(handle, path=..., offset=...)`.
3. Нужен обзор возможностей: `find_tools(query="""")` с `limit/nextOffset`.

### Что нельзя
- Вызывать тул, которого нет в текущем запросе (`unknown_tool`).
- Считать карточку схемой: аргументы появятся только после `load_tool_pack`.
- Пересказывать пользователю сырой JSON каталога вместо результата задачи.
";
