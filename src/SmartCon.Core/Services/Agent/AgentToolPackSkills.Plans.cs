    private const string Plans = @"## Пак plans: планы изменений

`execute_plan` — многошаговый сценарий одним подтверждением: план проверяется, шаги
выполняются по порядку, результат каждого шага верифицируется чтением.

### Карта тулов
- `execute_plan` — `goal` + `steps[]`; `planDigest` связывает превью с применением.

### Формат шага
`{stepId, toolName, arguments, dependsOn[], dryRun, expectedChanges|expectedChangesAtLeast,
readBackTool, readBackArguments, readBackExpectations[{path,expected}], rationale}`.
До 20 шагов. `dependsOn` задаёт порядок; по умолчанию шаги идут как перечислены.

### Кухня Revit
- В Revit нет программного Undo: после коммита операция необратима, откат — только
  компенсацией (вернуть старые значения, удалить созданное). Поэтому план проверяет шаги
  **до** записи, а не «потом откатим».
- Атомарность в Revit даёт `TransactionGroup`: внутренние транзакции выполняются,
  при сбое `RollBack` отменяет всю группу. `Commit` группы оставляет шаги отдельными
  пунктами в меню Undo — пользователь может откатить часть.
- Если следующий шаг зависит от применённого предыдущего (например, новый вид нужно
  разместить на листе), между ними нужна отдельная транзакция-барьер, иначе второй шаг
  не увидит первый.
- `Commit` может вернуть `Pending` (документ заморожен до ответа в диалоге предупреждений);
  это не успех. `IFailuresPreprocessor` в наших транзакциях подавляет ожидаемые
  предупреждения, но не скрывает реальные отказы.
- Частичный успех внутри одной транзакции недостижим: worksharing-ошибка откатывает весь
  scope. Наш исполнитель поэтому отчитывается по шагам и останавливается на отказе.

### Инварианты
- `dryRun=true` по умолчанию: план прогоняется в режиме превью и возвращает `planDigest`.
  Применение — тот же план с `dryRun=false` и этим digest; изменённый план требует нового
  превью (`plan_digest_mismatch`).
- `planDigest` считается по шагам (id, toolName, аргументы без `dryRun`, зависимости,
  ожидаемые количества) и документу; `goal` и `rationale` в него не входят — их можно
  уточнять, не ломая подтверждение.
- В превью шаги, зависящие от ещё не применённой записи, пропускаются
  (`preview_skipped: depends_on_unapplied_step`) — это нормально, но значит, что превью
  покрыло не всё; в apply они выполнятся.
- Apply: первый упавший шаг останавливает план (`plan_apply_failed`), уже применённые шаги
  остаются (у каждого свой change set), последующие получают `not_run`. **Автоматического
  откката плана нет** — откат по шагам через `undo_last` или `rollback_job`.
- `readBackExpectations` — обязательный способ доказать, что шаг сделал заявленное: путь +
  ожидаемое значение читаются после шага. Несовпадение попадает в `mismatches[]`, но общий
  `success` остаётся true — **сверяйте `mismatches`, а не только `success`**.
- `expectedChanges`/`expectedChangesAtLeast` — контракт количества; расхождение даёт
  `plan_fidelity_mismatch` ещё на превью.
- Шаг с `toolName`, которого нет в наборе доступных тулов, отклоняется на валидации: сначала
  `load_tool_pack`. `execute_plan` внутри шага запрещён.
- `allowDestructive=true` требуется для шагов, удаляющих данные; конфликт шаблон/настройки
  между шагами ловится как `plan_step_conflict`.

### Рецепты
1. «Настрой все планы этажа»: `get_view_settings` (шаг 1, чтение) → `configure_views`
   с `readBackExpectations` на итоговый `viewRange`.
2. «Переименуй виды и обнови шаблон»: два шага с `dependsOn`, у второго read-back
   `templateName`.
3. Перед планом соберите id: `list_views`/`query_elements` в отдельных вызовах, а в шаги
   передавайте уже готовые id — план не умеет «догадываться».

### Что нельзя
- Смешивать в одном шаге несколько несвязанных тулов — один шаг = один toolName.
- Заявлять успех по `success=true` без чтения `readBackExpectations`.
- Обещать откат Revit-овским Undo: откат делает `undo_last` (наши change sets) или
  `rollback_job`, и об этом надо сказать прямо.
";

    private const string Meta = @"## Пак meta: каталог и сохранённые результаты

### Карта тулов
- `find_tools` — поиск по каталогу: `query`, `pack`, `context`, `limit/offset`. Пустой запрос — весь каталог без схем.
- `read_tool_result` — чтение результата по `resultHandle` (offset/limit или path), когда ответ был обрезан бюджетом.

### Как устроен каталог
- 62 тула в 21 паке; в каждом запросе всегда есть исследовательское ядро (11 тулов) и системные
  тулы (`load_tool_pack`, `read_tool_result`, `execute_plan`). Всё остальное не появляется само:
  его надо найти (`find_tools`) и включить (`load_tool_pack`) — агент сам решает, что нужно
  задаче, а не короткий список по первому сообщению.
- `find_tools` возвращает **карточки**: имя, пакет, риск, назначение, признак `alreadyAvailable`
  и схему. Поиск отдаёт не больше 10 карточек (по умолчанию 5), `total` в поиске — это число
  возвращённых, а не всех совпадений.
- `packHasSkill=true` в карточке значит, что у пака есть markdown-мануал: загрузите пак
  (`load_tool_pack(pack=...)`) — скил придёт один раз за диалог. Ядро и системные тулы
  (`query_elements`, `get_element_details`, `list_views`, `execute_plan`…) вызываются без
  загрузки пака, но скил их пака — нет: перед первой записью загрузите write-пак (views,
  templates, filters, families…), а для полного контракта плана — пак plans.
- Пустой `query` — листинг каталога без схем: `limit` ≤100, пагинация `offset/nextOffset`,
  `truncated`. Один пакет — `pack`.
- Карточка не даёт права вызова: сначала `load_tool_pack`. Полные примеры/синонимы —
  через `fields` (`whenToUse`, `examples`, `synonyms`, `description`).
- Принцип трёх слоёв (как в MCP/Anthropic tool search): каталог → детали → выполнение.
  Аккуратные имена и первые строки описаний решают выбор — ищите словами пользователя
  («ведомость», «фильтр», «семейство»), а не внутренними терминами.

### Кухня контекста
- Точность выбора падает после 30–50 доступных инструментов, поэтому набор ограничен, а
  остальное живёт за поиском. Полные схемы приходят только для загруженного пака.
- Бюджет результата — 40 000 символов; у `load_tool_pack` он расширен до 90 000, потому что
  его скилы приходят один раз за диалог. При превышении массивы режутся структурно
  (`truncated`, `hint`) или ответ заменяется дайджестом с `resultHandle`; полный JSON
  доступен через `read_tool_result` (хранится 30 дней).
- `read_tool_result`: `handle` — идентификатор вызова тула, `offset`/`limit` (символы,
  по умолчанию 8000) или `path` внутрь JSON; ответ всегда содержит `nextOffset`.

### Инварианты
- `alreadyAvailable=true` или `alreadyLoaded` в ответе `load_tool_pack` — тул уже вызываем,
  повторная загрузка только тратит раунд.
- Если ответ обрезан и есть `resultHandle` — читайте его, а не повторяйте тот же вызов.
- Не загружайте весь каталог «на всякий случай»: каждый пак добавляет схемы и контекст.
- `find_tools` сам себя и `load_tool_pack` в выдачу не включает.

### Рецепты
1. Не знаете имя тула: `find_tools(query=""скрыть элементы на виде"")` → карточка → `load_tool_pack(pack=...)`.
2. Ответ пришёл с `truncated=true` и `resultHandle`: `read_tool_result(handle, offset=...)`.
3. Нужен обзор возможностей: `find_tools(query="""")` с `limit/nextOffset`.

### Что нельзя
- Вызывать тул, которого нет в текущем запросе (`unknown_tool`).
- Считать карточку схемой: аргументы появятся только после `load_tool_pack`.
- Пересказывать пользователю сырой JSON каталога вместо результата задачи.
";
